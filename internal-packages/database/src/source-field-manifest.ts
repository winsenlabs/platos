export function auditFieldTransformationManifest(
  expectedSourceFields: readonly string[],
  requiredTargetFields: readonly string[],
  sourceEntries: readonly SourceFieldTransformation[] = sourceFieldTransformationManifest,
  targetEntries: readonly RequiredTargetFieldContract[] = requiredTargetFieldManifest
): readonly string[] {
  const violations: string[] = [];
  const sourceCounts = new Map<string, number>();
  for (const entry of sourceEntries) {
    const path = `${entry.sourceModel}.${entry.sourceField}`;
    sourceCounts.set(path, (sourceCounts.get(path) ?? 0) + 1);
    if (
      (entry.disposition === "COPY" || entry.disposition === "TRANSFORM") &&
      entry.targetFields.length === 0
    ) {
      violations.push(`retained_source_without_target:${path}`);
    }
    if (
      (entry.disposition === "EXPORT" || entry.disposition === "DROP") &&
      entry.targetFields.length !== 0
    ) {
      violations.push(`discarded_source_with_target:${path}`);
    }
  }
  for (const path of expectedSourceFields) {
    const count = sourceCounts.get(path) ?? 0;
    if (count === 0) violations.push(`missing_source_disposition:${path}`);
    if (count > 1) violations.push(`duplicate_source_disposition:${path}`);
  }

  const targetCounts = new Map<string, number>();
  for (const entry of targetEntries) {
    targetCounts.set(entry.targetField, (targetCounts.get(entry.targetField) ?? 0) + 1);
    if (entry.sourceFields.length === 0 && !entry.deterministicDefault) {
      violations.push(`unsatisfied_target_requirement:${entry.targetField}`);
    }
    for (const sourceField of entry.sourceFields) {
      const sourceEntry = sourceEntries.find(
        (candidate) => `${candidate.sourceModel}.${candidate.sourceField}` === sourceField
      );
      if (!sourceEntry?.targetFields.includes(entry.targetField)) {
        violations.push(`target_source_not_mapped:${entry.targetField}:${sourceField}`);
      }
    }
  }
  for (const path of requiredTargetFields) {
    const count = targetCounts.get(path) ?? 0;
    if (count === 0) violations.push(`missing_target_requirement:${path}`);
    if (count > 1) violations.push(`duplicate_target_requirement:${path}`);
  }
  return violations.sort();
}
