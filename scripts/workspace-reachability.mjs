function sha256(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

function read(root, relativePath) {
  return fs.readFileSync(path.join(root, relativePath), "utf8");
}

function stable(value) {
  if (Array.isArray(value)) return value.map(stable);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, stable(value[key])])
    );
  }
  return value;
}

function stableJson(value) {
  return `${JSON.stringify(stable(value), null, 2)}\n`;
}

function parseWorkspacePatterns(text) {
  const patterns = [];
  let inPackages = false;
  for (const line of text.split(/\r?\n/)) {
    if (!inPackages) {
      if (/^packages:\s*$/.test(line)) inPackages = true;
      continue;
    }
    const item = line.match(/^\s+-\s+["']?([^"'#]+?)["']?\s*$/);
    if (item) patterns.push(item[1].trim());
    else if (/^[A-Za-z]/.test(line)) break;
  }
  if (patterns.length === 0) throw new Error("pnpm-workspace.yaml has no package patterns");
  return patterns;
}

function globRegex(pattern) {
  let out = "^";
  for (let index = 0; index < pattern.length; index += 1) {
    const character = pattern[index];
    if (character === "*" && pattern[index + 1] === "*") {
      out += ".*";
      index += 1;
    } else if (character === "*") out += "[^/]*";
    else if (character === "?") out += "[^/]";
    else out += character.replace(/[\\^$+?.()|[\]{}]/g, "\\$&");
  }
  return new RegExp(`${out}$`);
}

function allFiles(root) {
  const result = spawnSync(
    "git",
    ["ls-files", "-z", "--cached", "--others", "--exclude-standard"],
    { cwd: root, encoding: "buffer", maxBuffer: 64 * 1024 * 1024 }
  );
  if (result.error || result.status !== 0) {
    const detail = result.error?.message || result.stderr?.toString("utf8").trim() || `status ${result.status}`;
    throw new Error(`git ls-files failed while deriving repository candidates: ${detail}`);
  }
  if (result.stdout.length > 0 && result.stdout.at(-1) !== 0)
    throw new Error("git ls-files candidate output is not NUL-terminated");

  const decoder = new TextDecoder("utf-8", { fatal: true });
  const files = [];
  let start = 0;
  for (let index = 0; index < result.stdout.length; index += 1) {
    if (result.stdout[index] !== 0) continue;
    let relativePath;
    try {
      relativePath = decoder.decode(result.stdout.subarray(start, index));
    } catch {
      throw new Error(`git ls-files returned a candidate path with invalid UTF-8 at byte ${start}`);
    }
    start = index + 1;
    if (relativePath === "") continue;
    try {
      if (fs.lstatSync(path.join(root, relativePath)).isFile()) files.push(relativePath);
    } catch (error) {
      if (error?.code !== "ENOENT" && error?.code !== "ENOTDIR") throw error;
    }
  }
  return [...new Set(files)].sort((left, right) =>
    Buffer.compare(Buffer.from(left), Buffer.from(right))
  );
}

function workspaceInventory(root, files, workspaceText, parsed) {
  const matchers = parseWorkspacePatterns(workspaceText).map(globRegex);
  const manifestPaths = files.filter(
    (file) => file.endsWith("/package.json") || file === "package.json"
  );
  const workspaces = [];
  for (const manifestPath of manifestPaths) {
    const directory =
      manifestPath === "package.json" ? "." : manifestPath.slice(0, -"/package.json".length);
    if (directory === "." || !matchers.some((matcher) => matcher.test(directory))) continue;
    let manifest;
    try {
      manifest = JSON.parse(read(root, manifestPath));
    } catch (error) {
      throw new Error(`Malformed workspace manifest ${manifestPath}: ${error.message}`);
    }
    if (typeof manifest.name !== "string" || manifest.name === "") {
      throw new Error(`Registered workspace ${directory} has no package name`);
    }
    workspaces.push({
      path: directory,
      manifestPath,
      manifest,
      name: manifest.name,
      private: manifest.private === true,
    });
  }
  workspaces.sort((a, b) => a.path.localeCompare(b.path));

  const duplicateNames = workspaces
    .filter(
      (workspace, index) => workspaces.findIndex((other) => other.name === workspace.name) !== index
    )
    .map((workspace) => workspace.name);
  if (duplicateNames.length > 0) {
    throw new Error(
      `Duplicate workspace package name(s): ${[...new Set(duplicateNames)].sort().join(", ")}`
    );
  }

  const registered = workspaces.map((workspace) => workspace.path);
  const importers = Object.keys(parsed.importers)
    .filter((key) => key !== ".")
    .sort();
  const missingImporters = registered.filter((directory) => !parsed.importers[directory]);
  const staleImporters = importers.filter((directory) => !registered.includes(directory));
  if (missingImporters.length > 0 || staleImporters.length > 0) {
    throw new Error(
      [
        "Workspace registration/importer mismatch.",
        missingImporters.length > 0
          ? `Missing lockfile importer(s): ${missingImporters.join(", ")}`
          : "",
        staleImporters.length > 0
          ? `Unregistered lockfile importer(s): ${staleImporters.join(", ")}`
          : "",
      ]
        .filter(Boolean)
        .join(" ")
    );
  }
  return workspaces;
}

function localTarget(fromDirectory, value, parsed) {
  if (!value.startsWith("link:")) return null;
  const target = path.posix.normalize(path.posix.join(fromDirectory, value.slice("link:".length)));
  return parsed.importers[target] ? target : null;
}

function workspaceEdges(parsed, groups) {
  const edges = new Map();
  for (const directory of Object.keys(parsed.importers).sort()) {
    const targets = [];
    for (const group of groups) {
      for (const [name, value] of Object.entries(parsed.importers[directory][group] || {}).sort()) {
        const target = localTarget(directory, value, parsed);
        if (target) targets.push({ group, name, target });
      }
    }
    edges.set(
      directory,
      targets.sort((a, b) => `${a.target}:${a.name}`.localeCompare(`${b.target}:${b.name}`))
    );
  }
  return edges;
}

function validateManifestEdges(workspaces, parsed) {
  const byName = new Map(workspaces.map((workspace) => [workspace.name, workspace]));
  const manifestGroups = [
    ["dependencies", "prod"],
    ["optionalDependencies", "opt"],
    ["devDependencies", "dev"],
  ];
  for (const workspace of workspaces) {
    for (const [manifestGroup, lockGroup] of manifestGroups) {
      for (const dependencyName of Object.keys(workspace.manifest[manifestGroup] || {}).sort()) {
        const target = byName.get(dependencyName);
        if (!target) continue;
        const lockValue = parsed.importers[workspace.path]?.[lockGroup]?.[dependencyName];
        if (typeof lockValue !== "string") {
          throw new Error(
            `${workspace.manifestPath} declares local ${manifestGroup} ${dependencyName}, but its lockfile importer does not`
          );
        }
        const lockTarget = localTarget(workspace.path, lockValue, parsed);
        if (lockTarget !== target.path) {
          throw new Error(
            `${workspace.manifestPath} ${dependencyName} resolves to ${
              lockTarget || lockValue
            }, expected ${target.path}`
          );
        }
      }
    }
  }
}

function workspaceForPath(file, workspaces) {
  return (
    [...workspaces]
      .sort((a, b) => b.path.length - a.path.length)
      .find((workspace) => file === workspace.path || file.startsWith(`${workspace.path}/`)) || null
  );
}

function deriveImageRoots(root, files, workspaces) {
  const workflowFiles = files.filter(
    (file) => file.startsWith(".github/workflows/") && /\.ya?ml$/.test(file)
  );
  const dockerfiles = new Set();
  for (const file of workflowFiles) {
    const text = read(root, file);
    for (const match of text.matchAll(/\bdockerfile:\s*([^\s#]+)/g))
      dockerfiles.add(match[1].replace(/["']/g, ""));
  }
  if (dockerfiles.size === 0) throw new Error("No shipping Dockerfiles are declared by CI");

  const byName = new Map(workspaces.map((workspace) => [workspace.name, workspace.path]));
  const imageRoots = {};
  for (const dockerfile of [...dockerfiles].sort()) {
    if (!files.includes(dockerfile))
      throw new Error(`CI shipping Dockerfile is missing: ${dockerfile}`);
    const text = read(root, dockerfile);
    const roots = new Set();
    for (const match of text.matchAll(/--filter(?:=|\s+)["']?([^\s"']+)/g)) {
      const filter = match[1].replace(/\.{3}$/, "");
      if (byName.has(filter)) roots.add(byName.get(filter));
    }
    for (const workspace of workspaces) {
      if (text.includes(`${workspace.path}/package.json`)) roots.add(workspace.path);
    }
    if (roots.size === 0) {
      const owner = workspaceForPath(dockerfile, workspaces);
      if (owner) roots.add(owner.path);
    }
    if (roots.size !== 1) {
      throw new Error(
        `Shipping root for ${dockerfile} is ${
          roots.size === 0 ? "not derivable" : `ambiguous (${[...roots].join(", ")})`
        }`
      );
    }
    imageRoots[dockerfile] = [...roots][0];
  }
  return imageRoots;
}

function deriveApplicationRoots(root, files, workspaces, imageRoots) {
  const byName = new Map(workspaces.map((workspace) => [workspace.name, workspace.path]));
  const workspacePaths = new Set(workspaces.map((workspace) => workspace.path));
  const reasons = new Map();
  const add = (workspacePath, reason) => {
    if (!workspacePaths.has(workspacePath)) return;
    if (!reasons.has(workspacePath)) reasons.set(workspacePath, []);
    reasons.get(workspacePath).push(reason);
  };

  for (const workspace of workspaces) {
    const scripts = workspace.manifest.scripts || {};
    const executable =
      workspace.path.startsWith("apps/") &&
      (typeof workspace.manifest.main === "string" ||
        typeof workspace.manifest.bin === "string" ||
        (workspace.manifest.bin && typeof workspace.manifest.bin === "object") ||
        Object.keys(scripts).some((name) => name === "start" || name === "start:prod"));
    if (executable)
      add(workspace.path, {
        kind: "executable-manifest",
        from: workspace.manifestPath,
      });
  }

  const rootTsconfig = JSON.parse(read(root, "tsconfig.json"));
  for (const reference of rootTsconfig.references || []) {
    if (typeof reference?.path !== "string") continue;
    const workspacePath = path.posix.normalize(reference.path.replace(/^\.\//, ""));
    add(workspacePath, {
      kind: "root-typescript-reference",
      from: "tsconfig.json",
    });
  }

  const rootManifest = JSON.parse(read(root, "package.json"));
  const rootScripts = rootManifest.scripts || {};
  const invokedBuildScripts = new Set();
  for (const file of files.filter(isCi)) {
    const text = read(root, file);
    for (const match of text.matchAll(/\bpnpm(?:\s+run)?\s+([A-Za-z][A-Za-z0-9:_-]*)/g)) {
      if (match[1].includes("build") && Object.hasOwn(rootScripts, match[1]))
        invokedBuildScripts.add(match[1]);
    }
  }
  const pending = [...invokedBuildScripts];
  const expanded = new Set();
  while (pending.length > 0) {
    const script = pending.shift();
    if (expanded.has(script)) continue;
    expanded.add(script);
    const command = rootScripts[script] || "";
    for (const match of command.matchAll(/\bpnpm(?:\s+run)?\s+([A-Za-z][A-Za-z0-9:_-]*)/g)) {
      if (Object.hasOwn(rootScripts, match[1])) pending.push(match[1]);
    }
    for (const match of command.matchAll(/--filter(?:=|\s+)["']?([^\s"']+)/g)) {
      const packageName = match[1].replace(/^['"]|['"]$/g, "").replace(/\.{3}$/, "");
      add(byName.get(packageName), {
        kind: "ci-build-entrypoint",
        from: "package.json",
        script,
        packageName,
      });
    }
  }
  for (const [dockerfile, workspacePath] of Object.entries(imageRoots)) {
    if (workspacePath.startsWith("apps/"))
      add(workspacePath, {
        kind: "ci-image-build-entrypoint",
        from: dockerfile,
      });
  }

  for (const entries of reasons.values())
    entries.sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b)));
  return {
    roots: [...reasons.keys()].sort(),
    reasons: Object.fromEntries([...reasons.entries()].sort(([a], [b]) => a.localeCompare(b))),
  };
}

function graphEvidence(roots, edges) {
  const reachedBy = new Map();
  for (const root of [...new Set(roots)].sort()) {
    const queue = [[root, [root]]];
    const visited = new Set();
    while (queue.length > 0) {
      const [current, route] = queue.shift();
      if (visited.has(current)) continue;
      visited.add(current);
      if (!reachedBy.has(current)) reachedBy.set(current, []);
      reachedBy.get(current).push({ root, route });
      for (const edge of edges.get(current) || [])
        queue.push([edge.target, [...route, edge.target]]);
    }
  }
  for (const routes of reachedBy.values()) routes.sort((a, b) => a.root.localeCompare(b.root));
  return reachedBy;
}

function lineNumber(text, offset) {
  return text.slice(0, offset).split("\n").length;
}

function targetForSpecifier(specifier, sourceFile, workspaces) {
  for (const workspace of workspaces) {
    if (specifier === workspace.name || specifier.startsWith(`${workspace.name}/`))
      return workspace;
  }
  if (!specifier.startsWith(".")) return null;
  const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(sourceFile), specifier));
  return workspaceForPath(resolved, workspaces);
}

function emptyChannelEvidence(workspaces) {
  return new Map(workspaces.map((workspace) => [workspace.path, []]));
}

function addReason(channelEvidence, target, reason) {
  const reasons = channelEvidence.get(target.path);
  const key = JSON.stringify(reason);
  if (!reasons.some((existing) => JSON.stringify(existing) === key)) reasons.push(reason);
}

function sourceEvidence(root, files, workspaces, generatedFiles) {
  const staticEvidence = emptyChannelEvidence(workspaces);
  const dynamicEvidence = emptyChannelEvidence(workspaces);
  const codeFiles = files.filter(
    (file) =>
      SOURCE_EXTENSIONS.has(path.posix.extname(file)) &&
      !isTestFixture(file) &&
      !generatedFiles.has(file) &&
      file !== "scripts/workspace-reachability.mjs" &&
      file !== "scripts/workspace-reachability.test.mjs"
  );
  for (const file of codeFiles) {
    const owner = workspaceForPath(file, workspaces);
    const text = readTextFile(root, file);
    if (text === null) continue;
    const dynamicRanges = [];
    for (const match of text.matchAll(/\bimport\s*\(\s*["']([^"']+)["']\s*\)/g)) {
      dynamicRanges.push([match.index, match.index + match[0].length]);
      const target = targetForSpecifier(match[1], file, workspaces);
      if (target && target.path !== owner?.path)
        addReason(dynamicEvidence, target, {
          from: owner?.path || file,
          file,
          line: lineNumber(text, match.index),
          specifier: match[1],
        });
    }
    const patterns = [
      /\b(?:import|export)\s+(?:[^"']*?\s+from\s+)?["']([^"']+)["']/g,
      /\brequire\s*\(\s*["']([^"']+)["']\s*\)/g,
    ];
    for (const pattern of patterns) {
      for (const match of text.matchAll(pattern)) {
        if (dynamicRanges.some(([start, end]) => match.index >= start && match.index < end))
          continue;
        const target = targetForSpecifier(match[1], file, workspaces);
        if (target && target.path !== owner?.path)
          addReason(staticEvidence, target, {
            from: owner?.path || file,
            file,
            line: lineNumber(text, match.index),
            specifier: match[1],
          });
      }
    }
  }
  return { sourceStatic: staticEvidence, sourceDynamic: dynamicEvidence };
}

function isCi(file) {
  return file.startsWith(".github/workflows/") && /\.ya?ml$/.test(file);
}

function isDockerImage(file) {
  const base = path.posix.basename(file);
  return (
    /^Dockerfile(?:\.|$)/.test(base) ||
    file.startsWith("docker/") ||
    /^docker-compose.*\.ya?ml$/.test(file) ||
    file === ".dockerignore" ||
    /dockerfile/i.test(base)
  );
}

function isTestFixture(file) {
  return (
    /(^|\/)(?:test|tests|fixtures?|__tests__)(\/|$)/.test(file) ||
    /(?:^|\.)test\.[^.]+$/.test(path.posix.basename(file)) ||
    /(?:^|\.)spec\.[^.]+$/.test(path.posix.basename(file))
  );
}

function isDocsExamples(file) {
  return (
    /(^|\/)(?:docs?|content|examples?)(\/|$)/.test(file) ||
    /(^|\/)README(?:\.[^/]+)?$/i.test(file) ||
    /\.(?:md|mdx|rst)$/.test(file)
  );
}

function isLicense(file) {
  return (
    /(^|\/)(?:LICENSE|LICENCE|NOTICE)(?:\.[^/]*)?$/i.test(file) ||
    /license/i.test(path.posix.basename(file))
  );
}

function readTextFile(root, file) {
  const bytes = fs.readFileSync(path.join(root, file));
  if (bytes.length > 3_000_000 || bytes.includes(0)) return null;
  return bytes.toString("utf8");
}

function mentionsWorkspace(text, workspace) {
  return text.includes(workspace.name) || text.includes(workspace.path);
}

function deriveGeneratedOwnership(root, files, workspaces) {
  const outputOwners = new Map();
  const generators = [];
  if (files.includes(V1_GENERATOR_PATH)) {
    const result = spawnSync(process.execPath, [V1_GENERATOR_PATH, "--list"], {
      cwd: root,
      encoding: "utf8",
    });
    if (result.status !== 0)
      throw new Error(
        `${V1_GENERATOR_PATH} --list failed while deriving generated ownership:\n${result.stderr}`
      );
    const outputs = result.stdout.split(/\r?\n/).filter(Boolean).sort();
    if (new Set(outputs).size !== outputs.length)
      throw new Error(`${V1_GENERATOR_PATH} --list emitted duplicate owned outputs`);
    for (const output of outputs) {
      if (path.posix.isAbsolute(output) || output.split("/").includes(".."))
        throw new Error(`${V1_GENERATOR_PATH} --list emitted unsafe path: ${output}`);
      const absoluteOutput = path.join(root, output);
      if (
        !files.includes(output) ||
        !fs.existsSync(absoluteOutput) ||
        !fs.lstatSync(absoluteOutput).isFile()
      )
        throw new Error(
          `${V1_GENERATOR_PATH} --list owned output is missing or not a regular in-repository file: ${output}`
        );
      outputOwners.set(output, V1_GENERATOR_PATH);
    }
    generators.push({
      generator: V1_GENERATOR_PATH,
      outputCount: outputs.length,
      sha256: sha256(`${outputs.join("\n")}\n`),
    });
  }

  const explicitHeaders = new Set();
  for (const file of files) {
    const text = readTextFile(root, file);
    if (text !== null && GENERATED_HEADER.test(text.slice(0, 2048))) explicitHeaders.add(file);
  }
  const generatedFiles = new Set([...outputOwners.keys(), ...explicitHeaders]);
  const ownedOutputProjects = new Set();
  for (const file of outputOwners.keys()) {
    const owner = workspaceForPath(file, workspaces);
    if (owner) ownedOutputProjects.add(owner.path);
  }
  const projects = new Set();
  for (const file of generatedFiles) {
    const owner = workspaceForPath(file, workspaces);
    if (owner) projects.add(owner.path);
  }
  return {
    explicitHeaders,
    generatedFiles,
    outputOwners,
    summary: {
      generators,
      ownedOutputCount: outputOwners.size,
      ownedOutputProjectCount: ownedOutputProjects.size,
      ownedOutputProjects: [...ownedOutputProjects].sort(),
      explicitHeaderFileCount: explicitHeaders.size,
      generatedProjectCount: projects.size,
      generatedProjects: [...projects].sort(),
    },
  };
}

function patchedDependencyIdentity(dependencyAtVersion) {
  const separator = dependencyAtVersion.lastIndexOf("@");
  if (separator <= 0 || separator === dependencyAtVersion.length - 1)
    throw new Error(`Malformed pnpm.patchedDependencies key: ${dependencyAtVersion}`);
  return {
    name: dependencyAtVersion.slice(0, separator),
    version: dependencyAtVersion.slice(separator + 1),
  };
}

function snapshotRoutesForImporter(importer, parsed, importerGroups) {
  const importerRoutes = new Map();
  const snapshotRoutes = new Map();
  const queue = [];
  const addSnapshot = (snapshotKey, route) => {
    const existing = snapshotRoutes.get(snapshotKey);
    if (existing && existing.length <= route.length) return;
    snapshotRoutes.set(snapshotKey, route);
    queue.push(snapshotKey);
  };
  const addImporter = (directory, route) => {
    const existing = importerRoutes.get(directory);
    if (existing && existing.length <= route.length) return;
    importerRoutes.set(directory, route);
    const importerEntry = parsed.importers[directory];
    if (!importerEntry) return;
    for (const group of importerGroups) {
      for (const [name, value] of Object.entries(importerEntry[group] || {}).sort()) {
        const target = localTarget(directory, value, parsed);
        if (target) addImporter(target, [...route, target]);
        else addSnapshot(toSnapKey(name, value), [...route, `snapshot:${toSnapKey(name, value)}`]);
      }
    }
  };
  addImporter(importer, [importer]);
  while (queue.length > 0) {
    const snapshotKey = queue.shift();
    const route = snapshotRoutes.get(snapshotKey);
    const snapshot = parsed.snapshots[snapshotKey];
    if (!snapshot) continue;
    for (const group of ["deps", "opt"]) {
      for (const [name, value] of Object.entries(snapshot[group] || {}).sort()) {
        const target = toSnapKey(name, value);
        addSnapshot(target, [...route, `snapshot:${target}`]);
      }
    }
  }
  return snapshotRoutes;
}

export function patchesForImporter(
  importer,
  parsed,
  patchedDependencies,
  importerGroups = ["prod", "opt"]
) {
  const snapshotRoutes = snapshotRoutesForImporter(importer, parsed, importerGroups);
  const patches = [];
  for (const [dependencyAtVersion, patchFile] of Object.entries(patchedDependencies).sort()) {
    const expected = patchedDependencyIdentity(dependencyAtVersion);
    const snapshotKeys = [...snapshotRoutes.keys()]
      .filter((snapshotKey) => {
        const actual = parseKey(snapshotKey);
        return (
          Object.hasOwn(parsed.snapshots, snapshotKey) &&
          snapshotKey.includes("(patch_hash=") &&
          actual.name === expected.name &&
          actual.version === expected.version
        );
      })
      .sort();
    if (snapshotKeys.length > 0)
      patches.push({
        dependencyAtVersion,
        patchFile,
        snapshotKeys,
        reversePaths: snapshotKeys
          .map((snapshotKey) => snapshotRoutes.get(snapshotKey))
          .filter(Boolean),
      });
  }
  return patches;
}

export function reconcileConfiguredPatches(
  parsed,
  patchedDependencies,
  importers = Object.keys(parsed.importers)
) {
  const reconciliations = new Map(
    Object.entries(patchedDependencies)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([dependencyAtVersion, patchFile]) => [
        dependencyAtVersion,
        { dependencyAtVersion, patchFile, importerClosures: [] },
      ])
  );
  for (const importer of [...new Set(importers)].sort()) {
    const production = patchesForImporter(importer, parsed, patchedDependencies);
    const productionDependencies = new Set(production.map((patch) => patch.dependencyAtVersion));
    for (const patch of patchesForImporter(importer, parsed, patchedDependencies, [
      "prod",
      "opt",
      "dev",
    ])) {
      reconciliations.get(patch.dependencyAtVersion).importerClosures.push({
        importer,
        kind: productionDependencies.has(patch.dependencyAtVersion)
          ? "lockfile-production-snapshot-closure"
          : "lockfile-dev-only-snapshot-closure",
        snapshotKeys: patch.snapshotKeys,
        reversePaths: patch.reversePaths,
      });
    }
  }
  const patches = [...reconciliations.values()];
  const unreconciled = patches
    .filter((patch) => patch.importerClosures.length === 0)
    .map((patch) => patch.dependencyAtVersion);
  if (unreconciled.length > 0)
    throw new Error(
      `Configured patch lacks concrete lockfile snapshot reconciliation carrying patch_hash: ${unreconciled.join(
        ", "
      )}`
    );
  return {
    configuredPatchCount: patches.length,
    reconciledPatchCount: patches.length - unreconciled.length,
    patches,
  };
}

function repositoryChannelEvidence(root, files, workspaces, parsed) {
  const evidence = Object.fromEntries(
    CHANNELS.map((channel) => [channel, emptyChannelEvidence(workspaces)])
  );
  const generatedOwnership = deriveGeneratedOwnership(root, files, workspaces);
  Object.assign(
    evidence,
    sourceEvidence(root, files, workspaces, generatedOwnership.generatedFiles)
  );

  const rootManifest = JSON.parse(read(root, "package.json"));
  const manifests = [
    { path: ".", manifestPath: "package.json", manifest: rootManifest },
    ...workspaces,
  ];
  const rootTurboTasks = new Set();
  for (const command of Object.values(rootManifest.scripts || {})) {
    for (const match of command.matchAll(/\bturbo\s+run\s+([^\s&]+)/g))
      rootTurboTasks.add(match[1]);
  }
  for (const workspace of workspaces) {
    for (const [script, command] of Object.entries(workspace.manifest.scripts || {}).sort()) {
      addReason(evidence.packageScripts, workspace, {
        from: workspace.manifestPath,
        script,
        command,
        kind: "workspace-script",
      });
      if (script === "test" || script.startsWith("test:"))
        addReason(evidence.testsFixtures, workspace, {
          from: workspace.manifestPath,
          script,
          kind: "test-script",
        });
    }
    for (const task of [...rootTurboTasks].sort()) {
      if (Object.hasOwn(workspace.manifest.scripts || {}, task))
        addReason(evidence.packageScripts, workspace, {
          from: "package.json",
          script: task,
          kind: "root-turbo-task",
        });
    }
  }
  for (const manifest of manifests) {
    for (const [script, command] of Object.entries(manifest.manifest.scripts || {}).sort()) {
      for (const target of workspaces) {
        if (manifest.path !== target.path && mentionsWorkspace(command, target))
          addReason(evidence.packageScripts, target, {
            from: manifest.manifestPath,
            script,
            command,
            kind: "script-reference",
          });
      }
    }
  }

  const classifiers = [
    ["ci", isCi],
    ["dockerImage", isDockerImage],
    ["testsFixtures", isTestFixture],
    ["docsExamples", isDocsExamples],
    ["license", isLicense],
  ];
  for (const file of files) {
    if (
      file === JSON_PATH ||
      file === MARKDOWN_PATH ||
      file === "docs/vocabulary-boundary-exceptions.json" ||
      file.startsWith("docs/audits/sbom/advisory/") ||
      /docs\/audits\/sbom\/.*\.cdx\.json$/.test(file)
    )
      continue;
    const matchedClassifiers = classifiers.filter(([, classify]) => classify(file));
    if (matchedClassifiers.length === 0) continue;
    const text = readTextFile(root, file);
    if (text === null) continue;
    const owner = workspaceForPath(file, workspaces);
    for (const [channel] of matchedClassifiers) {
      for (const workspace of workspaces) {
        if (
          mentionsWorkspace(text, workspace) ||
          (owner?.path === workspace.path &&
            ["testsFixtures", "docsExamples", "license"].includes(channel))
        ) {
          const offset = Math.max(text.indexOf(workspace.name), text.indexOf(workspace.path), 0);
          addReason(evidence[channel], workspace, {
            from: file,
            line: lineNumber(text, offset),
            kind: owner?.path === workspace.path ? "workspace-owned-file" : "reference",
          });
        }
      }
      if (channel === "ci" && /\bpnpm\s+install\b(?![^\n]*--filter)/.test(text)) {
        for (const workspace of workspaces)
          addReason(evidence.ci, workspace, {
            from: file,
            kind: "workspace-wide-install",
          });
      }
    }
  }

  const patched = rootManifest.pnpm?.patchedDependencies || {};
  for (const patchFile of Object.values(patched)) {
    if (!files.includes(patchFile))
      throw new Error(`Configured patch file is missing: ${patchFile}`);
  }
  const patchReconciliation = reconcileConfiguredPatches(parsed, patched, [
    ".",
    ...workspaces.map((workspace) => workspace.path),
  ]);
  for (const patch of patchReconciliation.patches) {
    for (const importerClosure of patch.importerClosures) {
      const workspace = workspaces.find((candidate) => candidate.path === importerClosure.importer);
      if (!workspace) continue;
      addReason(evidence.patches, workspace, {
        from: workspace.path,
        file: patch.patchFile,
        dependency: patch.dependencyAtVersion,
        kind: importerClosure.kind,
        reversePaths: importerClosure.reversePaths,
        snapshotKeys: importerClosure.snapshotKeys,
      });
    }
  }
  for (const file of generatedOwnership.generatedFiles) {
    if (!files.includes(file)) continue;
    const text = readTextFile(root, file);
    if (text === null) continue;
    const owner = workspaceForPath(file, workspaces);
    if (owner)
      addReason(evidence.generated, owner, {
        from: file,
        generator: generatedOwnership.outputOwners.get(file) || null,
        kind: generatedOwnership.outputOwners.has(file)
          ? "generator-owned-output"
          : "explicit-generated-header",
      });
    if (generatedOwnership.explicitHeaders.has(file)) {
      for (const workspace of workspaces) {
        if (workspace.path !== owner?.path && mentionsWorkspace(text, workspace))
          addReason(evidence.generated, workspace, {
            from: file,
            kind: "explicit-generated-header-reference",
          });
      }
    }
  }
  for (const workspace of workspaces) {
    if (typeof workspace.manifest.license === "string")
      addReason(evidence.license, workspace, {
        from: workspace.manifestPath,
        license: workspace.manifest.license,
        kind: "manifest-license",
      });
  }

  for (const channel of CHANNELS) {
    for (const reasons of evidence[channel].values()) {
      reasons.sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b)));
    }
  }
  return {
    evidence,
    generatedOwnership: generatedOwnership.summary,
    patchReconciliation,
  };
}

function channelRecord(reasons) {
  const roots = [...new Set(reasons.map((reason) => reason.from))].sort();
  const reversePaths = reasons.flatMap(
    (reason) => reason.reversePaths || [[reason.from, reason.file || reason.from]]
  );
  return {
    reachable: reasons.length > 0,
    roots,
    reversePaths: reversePaths.filter(
      (route, index, all) =>
        all.findIndex((candidate) => JSON.stringify(candidate) === JSON.stringify(route)) === index
    ),
    reasons,
  };
}

function inputHashes(root, files) {
  const excluded = new Set([JSON_PATH, MARKDOWN_PATH]);
  const selected = files.filter(
    (file) => !excluded.has(file) && file !== ".git" && !file.startsWith(".git/")
  );
  const entries = selected.map((file) => ({
    path: file,
    sha256: sha256(fs.readFileSync(path.join(root, file))),
  }));
  return {
    aggregateSha256: sha256(entries.map((entry) => `${entry.sha256}  ${entry.path}\n`).join("")),
    files: entries,
  };
}

function statusFor(workspace, ociImage, applicationDeployable, deploymentUnion, channels) {
  if (ociImage) return "retain-oci-image";
  if (applicationDeployable) return "retain-application-deployable";
  if (deploymentUnion) return "retain-deployment-union";
  if (!workspace.private) return "owner-review-public-boundary";
  if (
    channels.sourceStatic.reachable ||
    channels.sourceDynamic.reachable ||
    channels.ci.reachable ||
    channels.dockerImage.reachable
  )
    return "owner-review-repository-referenced";
  if (CHANNELS.some((channel) => channels[channel].reachable))
    return "owner-review-nonproduction-referenced";
  return "owner-review-unreferenced";
}

export function buildReachabilityReport(root = DEFAULT_ROOT) {
  const files = allFiles(root);
  const workspaceText = read(root, "pnpm-workspace.yaml");
  const lock = loadLockfile(path.join(root, "pnpm-lock.yaml"));
  const workspaces = workspaceInventory(root, files, workspaceText, lock.parsed);
  validateManifestEdges(workspaces, lock.parsed);
  if (workspaces.length === 0)
    throw new Error("Reachability report would be vacuous: zero registered workspaces");

  const imageRoots = deriveImageRoots(root, files, workspaces);
  const ociImageRoots = [...new Set(Object.values(imageRoots))].sort();
  if (ociImageRoots.length === 0)
    throw new Error("Reachability report would be vacuous: zero production roots");
  const applicationRoots = deriveApplicationRoots(root, files, workspaces, imageRoots);
  if (applicationRoots.roots.length === 0)
    throw new Error("Reachability report would be vacuous: zero application/deployable roots");
  const productionEdges = workspaceEdges(lock.parsed, ["prod", "opt"]);
  const developmentEdges = workspaceEdges(lock.parsed, ["prod", "opt", "dev"]);
  const ociImageEvidence = graphEvidence(ociImageRoots, productionEdges);
  const applicationEvidence = graphEvidence(applicationRoots.roots, productionEdges);
  const deploymentUnionRoots = [...new Set([...ociImageRoots, ...applicationRoots.roots])].sort();
  const deploymentUnionEvidence = graphEvidence(deploymentUnionRoots, productionEdges);
  const developmentEvidence = graphEvidence(ociImageRoots, developmentEdges);
  const channelResult = repositoryChannelEvidence(root, files, workspaces, lock.parsed);
  const channels = channelResult.evidence;

  const imageRootReasons = Object.fromEntries(
    ociImageRoots.map((workspacePath) => [
      workspacePath,
      Object.entries(imageRoots)
        .filter(([, rootPath]) => rootPath === workspacePath)
        .map(([dockerfile]) => ({ kind: "ci-shipping-dockerfile", from: dockerfile })),
    ])
  );
  const unionRootReasons = Object.fromEntries(
    deploymentUnionRoots.map((workspacePath) => [
      workspacePath,
      [
        ...(imageRootReasons[workspacePath] || []),
        ...(applicationRoots.reasons[workspacePath] || []),
      ],
    ])
  );
  const closureRecord = (routes, groups, rootReasons) => ({
    reachable: routes.length > 0,
    roots: routes.map((route) => route.root),
    reversePaths: routes.map((route) => route.route),
    reasons: routes.map((route) => ({
      root: route.root,
      path: route.route,
      groups,
      rootReasons: rootReasons[route.root] || [],
    })),
  });

  const workspaceRecords = workspaces.map((workspace) => {
    const ociImageRoutes = ociImageEvidence.get(workspace.path) || [];
    const applicationRoutes = applicationEvidence.get(workspace.path) || [];
    const deploymentUnionRoutes = deploymentUnionEvidence.get(workspace.path) || [];
    const developmentRoutes = developmentEvidence.get(workspace.path) || [];
    const channelRecords = Object.fromEntries(
      CHANNELS.map((channel) => [channel, channelRecord(channels[channel].get(workspace.path))])
    );
    const ociImage = ociImageRoutes.length > 0;
    const applicationDeployable = applicationRoutes.length > 0;
    const deploymentUnion = deploymentUnionRoutes.length > 0;
    const candidateStatus = statusFor(
      workspace,
      ociImage,
      applicationDeployable,
      deploymentUnion,
      channelRecords
    );
    const record = {
      path: workspace.path,
      name: workspace.name,
      private: workspace.private,
      manifestSha256: sha256(read(root, workspace.manifestPath)),
      ociImageClosure: closureRecord(
        ociImageRoutes,
        ["dependencies", "optionalDependencies"],
        imageRootReasons
      ),
      applicationDeployableClosure: closureRecord(
        applicationRoutes,
        ["dependencies", "optionalDependencies"],
        applicationRoots.reasons
      ),
      deploymentUnionClosure: closureRecord(
        deploymentUnionRoutes,
        ["dependencies", "optionalDependencies"],
        unionRootReasons
      ),
      repositoryDevClosure: closureRecord(
        developmentRoutes,
        ["dependencies", "optionalDependencies", "devDependencies"],
        imageRootReasons
      ),
      channels: channelRecords,
      candidate: {
        reviewCandidate: !deploymentUnion,
        status: candidateStatus,
        deletionAuthorized: false,
        basis: deploymentUnion
          ? "Derived dependency path from the current OCI image or application/deployable graph."
          : "No OCI image or application/deployable dependency path; channel evidence is retained for owner review and is not deletion authorization.",
      },
      boundaries: {
        kind: !workspace.private
          ? "external-public-package"
          : /^(?:apps|internal-packages)\//.test(workspace.path)
          ? "embedded-private-implementation"
          : "private-workspace",
        externalPublic: !workspace.private,
        externalPublicReasons: !workspace.private ? ["package.json does not set private:true"] : [],
        ownerDecisionRequired: !deploymentUnion,
        ownerDecisionReasons: !deploymentUnion
          ? [
              "non-production classification is candidate evidence only; deletion requires separate authorization",
            ]
          : [],
      },
    };
    return { ...record, evidenceSha256: sha256(stableJson(record)) };
  });

  const imageExternalNodes = {};
  for (const [image, definition] of Object.entries(IMAGES)) {
    imageExternalNodes[image] = computeClosure(definition.roots, lock.parsed).size;
  }
  const report = {
    schemaVersion: 2,
    issue: "WIN-253",
    derivation: {
      manualReachabilityAssertionsAccepted: false,
      deletionAuthorized: false,
      workspaceRegistration:
        "filesystem package.json paths matched by pnpm-workspace.yaml, exact-set checked against lockfile importers",
      ociImage:
        "dependencies + optionalDependencies from roots derived from CI-declared shipping Dockerfiles",
      applicationDeployable:
        "dependencies + optionalDependencies from executable app manifests, root TypeScript project references, and CI build entrypoints",
      deploymentUnion:
        "union of the independently derived OCI image and application/deployable closures",
      repositoryDev: "OCI image roots plus devDependencies",
      generated:
        "explicit generated-file headers plus existing regular in-repository generator --list outputs; path names do not assert generated ownership",
      patches:
        "root and workspace importer production/dev snapshot closures intersected with pnpm.patchedDependencies; every configured patch must reconcile to a resolved snapshot carrying patch_hash",
      channels: CHANNELS,
    },
    roots: {
      shippingDockerfiles: imageRoots,
      ociImageRoots,
      applicationDeployable: applicationRoots,
      deploymentUnionRoots,
      repositoryRegistration: workspaces.map((workspace) => workspace.path),
    },
    generatedOwnership: channelResult.generatedOwnership,
    patchReconciliation: channelResult.patchReconciliation,
    summary: {
      registeredWorkspaceCount: workspaces.length,
      ociImageWorkspaceCount: workspaceRecords.filter(
        (workspace) => workspace.ociImageClosure.reachable
      ).length,
      applicationDeployableWorkspaceCount: workspaceRecords.filter(
        (workspace) => workspace.applicationDeployableClosure.reachable
      ).length,
      deploymentUnionWorkspaceCount: workspaceRecords.filter(
        (workspace) => workspace.deploymentUnionClosure.reachable
      ).length,
      repositoryDevWorkspaceCount: workspaceRecords.filter(
        (workspace) => workspace.repositoryDevClosure.reachable
      ).length,
      installTraversalWorkspaceCount: workspaces.length,
      reviewCandidateCount: workspaceRecords.filter(
        (workspace) => workspace.candidate.reviewCandidate
      ).length,
      publicBoundaryCount: workspaceRecords.filter(
        (workspace) => workspace.boundaries.externalPublic
      ).length,
      configuredPatchCount: channelResult.patchReconciliation.configuredPatchCount,
      reconciledPatchCount: channelResult.patchReconciliation.reconciledPatchCount,
      externalProductionSnapshotNodesByImage: imageExternalNodes,
      channelReachableCounts: Object.fromEntries(
        CHANNELS.map((channel) => [
          channel,
          workspaceRecords.filter((workspace) => workspace.channels[channel].reachable).length,
        ])
      ),
    },
    inputs: inputHashes(root, files),
    workspaces: workspaceRecords,
  };
  assert.equal(report.summary.registeredWorkspaceCount, report.workspaces.length);
  const evidenceSha256 = sha256(stableJson(report));
  return { ...report, evidenceSha256 };
}

