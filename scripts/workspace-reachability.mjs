export function artifactBytes(report) {
  return {
    [JSON_PATH]: stableJson(report),
    [MARKDOWN_PATH]: renderMarkdown(report),
  };
}

export function generateArtifacts(root = DEFAULT_ROOT) {
  const report = buildReachabilityReport(root);
  for (const [relativePath, bytes] of Object.entries(artifactBytes(report))) {
    fs.mkdirSync(path.dirname(path.join(root, relativePath)), { recursive: true });
    fs.writeFileSync(path.join(root, relativePath), bytes);
  }
  return report;
}

export function checkArtifacts(root = DEFAULT_ROOT) {
  const report = buildReachabilityReport(root);
  const drift = [];
  for (const [relativePath, expected] of Object.entries(artifactBytes(report))) {
    const absolutePath = path.join(root, relativePath);
    const actual = fs.existsSync(absolutePath) ? fs.readFileSync(absolutePath, "utf8") : null;
    if (actual !== expected)
      drift.push({
        path: relativePath,
        expectedSha256: sha256(expected),
        actualSha256: actual === null ? null : sha256(actual),
      });
  }
  if (drift.length > 0) {
    throw new Error(
      `Workspace reachability artifact drift:\n${drift
        .map(
          (item) =>
            `- ${item.path}: expected ${item.expectedSha256}, actual ${
              item.actualSha256 || "missing"
            }`
        )
        .join("\n")}\nRun: node scripts/workspace-reachability.mjs generate`
    );
  }
  return report;
}

function main() {
  const [command = "check", ...args] = process.argv.slice(2);
  let root = DEFAULT_ROOT;
  for (let index = 0; index < args.length; index += 1) {
    if (args[index] === "--root" && args[index + 1]) root = path.resolve(args[++index]);
    else throw new Error(`Unknown argument: ${args[index]}`);
  }
  if (!["check", "generate"].includes(command))
    throw new Error(
      `Usage: node scripts/workspace-reachability.mjs [check|generate] [--root PATH]`
    );
  const report = command === "generate" ? generateArtifacts(root) : checkArtifacts(root);
  console.log(
    `WIN-253 workspace reachability ${command} PASSED: ${report.summary.registeredWorkspaceCount} registered, ${report.summary.ociImageWorkspaceCount} OCI, ${report.summary.applicationDeployableWorkspaceCount} application/deployable, ${report.summary.deploymentUnionWorkspaceCount} union, ${report.summary.reviewCandidateCount} review candidates.`
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === SCRIPT_PATH) {
  try {
    main();
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
